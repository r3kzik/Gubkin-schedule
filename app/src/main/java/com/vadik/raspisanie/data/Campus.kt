    private val ROOM_RE = Regex("^\\s*(\\d{3,4})\\s*([а-яёa-z])?", RegexOption.IGNORE_CASE)

    /**
     * Где находится аудитория по её номеру из расписания:
     * «2358» → 3 корпус, 3 этаж; «725» → главный, 7 этаж; «1104» → 2 корпус, 1 этаж.
     */
    fun locate(roomText: String?): RoomLocation? {
        if (roomText.isNullOrBlank()) return null
        val text = roomText.trim()
        val low = text.lowercase()
        if ("баа" in low || "большая академическая" in low) {
            return RoomLocation(building("main"), null, "БАА", "Большая академическая аудитория — вход из главного (1) корпуса")
        }
        if ("спортзал" in low || "спортивный зал" in low) {
            return RoomLocation(building("k2"), 0, text, "Спортзалы № 1–3 — в цокольном этаже 2 корпуса")
        }
        val m = ROOM_RE.find(text) ?: return null
        val digits = m.groupValues[1]
        val room = digits + m.groupValues[2]
        return when (digits.length) {
            3 -> RoomLocation(building("main"), digits[0].digitToInt(), room)
            4 -> {
                val floor = digits[1].digitToInt()
                when (digits[0]) {
                    '1' -> RoomLocation(building("k2"), floor, room)
                    '2' -> RoomLocation(
                        building("k3"), floor, room,
                        "Из главного корпуса в 3 корпус можно пройти через столовую на 2 этаже",
                    )
                    '5' -> RoomLocation(building("lib"), floor, room)
                    else -> null
                }
            }
            else -> null
        }
    }

    /** Поиск по местам путеводителя. */
    fun searchPois(query: String): List<Poi> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()
        return pois.filter { p ->
            p.title.lowercase().contains(q) || p.room?.lowercase()?.startsWith(q) == true ||
                building(p.buildingId).short.lowercase().contains(q)
        }
    }
