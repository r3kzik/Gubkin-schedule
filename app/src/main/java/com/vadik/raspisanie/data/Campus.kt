 *   3 корпус            — «2 + этаж + номер»    (2435 → 4 этаж)
 *   Библиотека          — «5 + этаж + номер»    (5810 → 8 этаж)
 */
data class Building(
    val id: String,
    val name: String,
    val short: String,
    /** Как читать номер аудитории в этом корпусе. */
    val numbering: String?,
    val description: String,
)

data class Poi(
    val title: String,
    val buildingId: String,
    /** «3 этаж», «цокольный этаж», «портретная галерея» … */
    val floor: String?,
    val room: String? = null,
    val category: String,
)

data class RoomLocation(
    val building: Building,
    /** Номер этажа (0 — цокольный) или null, если по номеру не определить. */
    val floor: Int?,
    val room: String,
    val note: String? = null,
) {
    val floorLabel: String?
        get() = when (floor) {
            null -> null
            0 -> "цокольный этаж"
            else -> "$floor этаж"
        }

    /** «3 корпус · 3 этаж» */
    val summary: String
        get() = listOfNotNull(building.short, floorLabel).joinToString(" · ")
}

